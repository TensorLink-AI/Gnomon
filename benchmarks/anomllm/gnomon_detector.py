"""Gnomon treatment for the AnomLLM benchmark.

Reads the official synthetic datasets (``data/synthetic/<name>/eval/
data.pkl``, generated by the official ``synthesize.sh``), runs Gnomon's
graded anomaly detection on each series, and writes predictions to the
official results tree (``results/synthetic/<name>/gnomon/<variant>.jsonl``)
in the exact row format the official ``result_agg.py`` consumes. The
official aggregator then scores Gnomon and every LLM variant with the same
F1 / affiliation-F1 code, unmodified.

Adapter decisions, disclosed:

- The benchmark's series are plain value arrays with no timestamps.
  Gnomon requires a regular time axis, so one is synthesised (hourly UTC
  from a fixed epoch). The axis is arbitrary but identical across
  conditions and does not enter the metric, which is index-based.
- Detection runs through ``gnomon.anomaly.detect_anomalies`` — the same
  competing-detector grading used by ``gnomon detect`` — with Gnomon's
  default threshold unless overridden. No labels are supplied: selection
  is by synthetic-injection F1, exactly as an operator without ground
  truth would run it.
- Flagged points are converted to the benchmark's half-open
  ``{"start": s, "end": e}`` intervals by merging consecutive indices.
- The adapter's own GnomonBench sidecar goes to ``gnomonbench/synthetic/
  <name>/<model>/`` in the checkout — outside ``results/``, which the
  official aggregator sweeps for every non-``requests`` ``*.jsonl``. A
  sidecar written under ``results/`` once showed up in the official
  table as a phantom all-zero variant.
"""

from __future__ import annotations

import json
import pickle
import re
import sys
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from benchmarks.common.records import RecordWriter, RunRecord  # noqa: E402

EPOCH = datetime(2024, 1, 1, tzinfo=timezone.utc)
STEP = timedelta(hours=1)


def flagged_indices_to_intervals(indices: list[int]) -> list[dict[str, int]]:
    """Merge sorted flagged indices into half-open intervals.

    ``[3, 4, 5, 9]`` becomes ``[{"start": 3, "end": 6}, {"start": 9,
    "end": 10}]``, matching the benchmark's ``interval_to_vector``
    convention (``vector[start:end] = 1``).
    """
    intervals: list[dict[str, int]] = []
    for index in sorted(set(int(i) for i in indices)):
        if intervals and index == intervals[-1]["end"]:
            intervals[-1]["end"] = index + 1
        else:
            intervals.append({"start": index, "end": index + 1})
    return intervals


def intervals_to_vector(intervals: list[Any], length: int) -> list[int]:
    """Pure-python mirror of the benchmark's ``interval_to_vector``,
    used only for the adapter's own per-series F1 bookkeeping."""
    vector = [0] * length
    for entry in intervals:
        if isinstance(entry, dict):
            start, end = int(entry["start"]), int(entry["end"])
        else:
            start, end = int(entry[0]), int(entry[1])
        start = max(0, min(start, length))
        end = max(start, min(end, length))
        for position in range(start, end):
            vector[position] = 1
    return vector


def binary_f1(truth: list[int], prediction: list[int]) -> float:
    """Pointwise F1 under the official AnomLLM convention.

    More than half of AnomLLM's synthetic series carry no anomaly at
    all, and the official ``compute_metrics`` scores a clean series with
    an empty prediction as every metric = 1.0, included in the mean. The
    preview follows the same convention — an earlier version excluded
    those series from the mean instead, which made the preview read
    systematically lower than the official table. Correct silence is
    still tallied separately (``clean_series_correctly_silent``) so it
    stays visible rather than dissolving into the mean.
    """
    true_positive = sum(1 for t, p in zip(truth, prediction) if t and p)
    predicted = sum(prediction)
    actual = sum(truth)
    if actual == 0 and predicted == 0:
        return 1.0
    if actual == 0 or predicted == 0 or true_positive == 0:
        return 0.0
    precision = true_positive / predicted
    recall = true_positive / actual
    return 2 * precision * recall / (precision + recall)


#: Variant names whose files upstream ``postprocess_configs`` rescales
#: (every integer multiplied by an inverse scale) at aggregation time.
RESCALED_VARIANT = re.compile(r"^[01]shot-text-s\d+(?:\.\d+)?(?:-cot)?$")


def default_records_path(
    anomllm_root: Path, data_name: str, model_dir: str, variant_name: str
) -> Path:
    """Where the adapter's own GnomonBench sidecar lands: a parallel
    ``gnomonbench/`` tree, deliberately outside ``results/``.

    Upstream's ``collect_results`` walks everything under ``results/``
    and scores every ``*.jsonl`` whose name lacks ``requests`` as a
    model variant. A sidecar written there once rendered a phantom
    all-zero "gnomon" row in the official table, so the sidecar's
    default home is outside the tree the official aggregator owns.
    """
    return (anomllm_root / "gnomonbench" / "synthetic" / data_name
            / model_dir / f"{variant_name}.gnomonbench.jsonl")


def shield_from_official_scoring(path: Path, anomllm_root: Path) -> Path:
    """Belt and braces for caller-supplied sidecar paths: any path that
    still lands inside the official ``results/`` tree gets ``requests``
    inserted into its filename, which upstream's ``collect_results``
    filter (``'requests' not in file``) skips instead of scoring."""
    path = Path(path)
    try:
        path.resolve().relative_to((anomllm_root / "results").resolve())
    except ValueError:
        return path
    if "requests" in path.name:
        return path
    return path.with_name(f"{path.stem}.requests{path.suffix}")


def load_eval_dataset(anomllm_root: Path, data_name: str) -> dict[str, list[Any]]:
    data_path = anomllm_root / "data" / "synthetic" / data_name / "eval" / "data.pkl"
    if not data_path.exists():
        raise FileNotFoundError(
            f"{data_path} not found. Generate the official datasets first "
            "(run synthesize.sh in the AnomLLM checkout, or download their "
            "prebuilt archive)."
        )
    with data_path.open("rb") as handle:
        payload = pickle.load(handle)
    return {"series": payload["series"], "anom": payload["anom"]}


def series_values(series: Any) -> list[float]:
    """Flatten one benchmark series (shape ``(T, 1)`` or ``(T,)``) to floats."""
    values: list[float] = []
    for row in series:
        try:
            values.append(float(row[0]))
        except (TypeError, IndexError):
            values.append(float(row))
    return values


def detect_series(values: list[float], threshold: float | None) -> dict[str, Any]:
    """Run Gnomon's graded detection on one series."""
    from gnomon.anomaly import DEFAULT_THRESHOLD, detect_anomalies
    from gnomon.temporal import detect_season

    timestamps = [(EPOCH + STEP * i).isoformat() for i in range(len(values))]
    season, _, _ = detect_season(values, "h")
    return detect_anomalies(
        timestamps,
        values,
        season=season,
        threshold=DEFAULT_THRESHOLD if threshold is None else threshold,
    )


def ground_truth_intervals(anom_entry: Any) -> list[Any] | None:
    """Best-effort extraction of sensor-0 ground-truth intervals, mirroring
    the aggregator's ``eval_dataset[i][0][0]`` access. Returns None when the
    stored shape is unexpected; the official aggregator remains the
    authoritative scorer either way."""
    try:
        sensor = anom_entry[0]
        return [
            {"start": int(pair[0]), "end": int(pair[1])}
            for pair in sensor
        ]
    except (TypeError, IndexError, ValueError):
        return None


def run_gnomon_condition(
    anomllm_root: Path,
    data_name: str,
    *,
    threshold: float | None = None,
    variant_name: str = "detect",
    model_dir: str = "gnomon",
    records_path: Path | None = None,
) -> dict[str, Any]:
    """Produce the Gnomon prediction file for one dataset.

    Writes ``results/synthetic/<data>/<model_dir>/<variant>.jsonl`` inside
    the AnomLLM checkout, a GnomonBench sidecar under the adapter-owned
    ``gnomonbench/`` tree (never under ``results/``, which the official
    aggregator sweeps), and returns a run summary.
    """
    # Enforced here, not just at the CLI: the official aggregator
    # rescales every integer in files under these variant names,
    # silently corrupting full-resolution indices.
    if RESCALED_VARIANT.match(variant_name):
        raise ValueError(
            f"variant name {variant_name!r} triggers upstream "
            f"postprocess_configs index rescaling; pick another name"
        )
    dataset = load_eval_dataset(anomllm_root, data_name)
    results_dir = anomllm_root / "results" / "synthetic" / data_name / model_dir
    results_dir.mkdir(parents=True, exist_ok=True)
    results_path = results_dir / f"{variant_name}.jsonl"
    if results_path.exists():
        results_path.unlink()

    sidecar_path = shield_from_official_scoring(
        records_path
        or default_records_path(anomllm_root, data_name, model_dir,
                                variant_name),
        anomllm_root,
    )
    # RecordWriter appends; a rerun must replace the previous run's
    # sidecar rows just as it replaces the official predictions file.
    sidecar_path.unlink(missing_ok=True)
    records = RecordWriter(sidecar_path)
    f1_scores: list[float] = []
    clean_correct = 0
    supported = 0
    for number, series in enumerate(dataset["series"], start=1):
        values = series_values(series)
        started = time.time()
        detection = detect_series(values, threshold)
        elapsed = time.time() - started
        flagged = [
            round((datetime.fromisoformat(a["timestamp"]) - EPOCH) / STEP)
            for a in detection["anomalies"]
        ]
        intervals = flagged_indices_to_intervals(flagged)
        custom_id = f"{data_name}_{model_dir}_{variant_name}_{number:05d}"
        row = {
            "custom_id": custom_id,
            "request": {
                "adapter": "gnomon",
                "detector": detection.get("detector"),
                "selection_basis": detection.get("selection_basis"),
                "support": detection.get("support", {}).get("status"),
            },
            "response": json.dumps(intervals),
        }
        with results_path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(row) + "\n")

        status = detection.get("support", {}).get("status")
        if status in ("supported", "conditionally_supported"):
            supported += 1
        f1 = None
        truth = ground_truth_intervals(dataset["anom"][number - 1])
        if truth is not None:
            truth_vector = intervals_to_vector(truth, len(values))
            prediction_vector = intervals_to_vector(intervals, len(values))
            f1 = binary_f1(truth_vector, prediction_vector)
            f1_scores.append(f1)
            if sum(truth_vector) == 0 and sum(prediction_vector) == 0:
                # Correctly quiet on a series with nothing to find —
                # scores 1.0 under the official convention, and counted
                # here so the silence stays visible in the summary.
                clean_correct += 1
        records.write(RunRecord(
            task_id=custom_id,
            success=bool(detection.get("detector")),
            appropriate_abstention=detection.get("detector") is None,
            tool_calls=1,
            latency_seconds=round(elapsed, 4),
            extra={"f1": f1, "support": status,
                   "detector": detection.get("detector")},
        ))

    summary = {
        "benchmark": "anomllm",
        "data": data_name,
        "condition": f"{model_dir}/{variant_name}",
        "series": len(dataset["series"]),
        "supported": supported,
        "scored_series": len(f1_scores),
        "clean_series_correctly_silent": clean_correct,
        "preview_mean_pointwise_f1_official_convention": (
            sum(f1_scores) / len(f1_scores) if f1_scores else None
        ),
        "results_file": str(results_path),
        "gnomonbench_file": str(records.path),
        "note": (
            "Official scores come from result_agg.py in the AnomLLM "
            "checkout. The preview mean follows the official convention "
            "— a clean series with an empty prediction scores 1.0 and "
            "is included in the mean — so it tracks the official table; "
            "result_agg.py remains the authoritative scorer."
        ),
    }
    return summary
