"""Deterministic generator for temporal-leakage trap tasks.

A trap task is a bitemporal series in which **peeking past the cutoff
measurably helps**. That property is what makes the family a measurement
rather than an assertion: if leaking did not help, a forecaster that refuses
to leak would give up nothing, and "structurally cannot leak" would be a
guarantee about a harm nobody was at risk of.

The construction has two parts, both drawn from how revised data actually
behaves:

- **A shock at the cutoff.** The horizon opens with a level shift that
  nothing in the pre-cutoff history predicts. Any forecaster restricted to
  what was known at the cutoff must miss it; a forecaster that reads the
  post-cutoff rows tracks it exactly. This is the near-binary signal.
- **Late revisions to recent history.** The last few pre-cutoff observations
  are first published low and corrected upward after the cutoff. A leaker
  also gets the corrected recent level, which is the graded advantage.

Every row lives in one CSV with a ``published`` column, exactly as a real
revision-carrying extract would. The post-cutoff rows are *present in the
file* — that is the trap. Nothing is hidden; what is tested is whether the
forecaster respects the publication dates.

Generation is seeded and pure, so a task set is reproducible from
``(count, seed)`` alone and can be regenerated by anyone checking a result.
"""

from __future__ import annotations

import csv
import math
import random
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

#: Fraction by which the last `REVISION_LAG` pre-cutoff observations are
#: under-reported on first publication, before being corrected.
REVISION_UNDERSTATEMENT = (0.06, 0.18)
REVISION_LAG = 6

#: Shock size as a fraction of the series level, applied from the cutoff.
#: Signed, so a leaker cannot profit by always guessing "up".
SHOCK_MAGNITUDE = (0.18, 0.35)


@dataclass
class TrapTask:
    task_id: str
    rows: list[dict[str, Any]]          # every row, with valid and known times
    cutoff: datetime
    horizon: int
    truth: list[float]                  # what actually happened after the cutoff
    shock: float                        # signed level shift, fraction of level
    understatement: float               # revision size, fraction
    frequency: str = "D"
    metadata: dict[str, Any] = field(default_factory=dict)

    def visible_rows(self) -> list[dict[str, Any]]:
        """Rows a forecaster restricted to the cutoff may use."""
        return [row for row in self.rows
                if datetime.fromisoformat(row["published"]) <= self.cutoff]

    def vintage_values(self) -> list[float]:
        """The series as it stood at the cutoff: latest value per timestamp
        among rows published by then."""
        latest: dict[str, tuple[str, float]] = {}
        for row in self.visible_rows():
            stamp, published = row["timestamp"], row["published"]
            if stamp not in latest or published > latest[stamp][0]:
                latest[stamp] = (published, float(row["value"]))
        return [latest[key][1] for key in sorted(latest)]

    def revised_values(self) -> list[float]:
        """The series as it stands *now*, including everything published
        after the cutoff. Using this to forecast is the leak."""
        latest: dict[str, tuple[str, float]] = {}
        for row in self.rows:
            stamp, published = row["timestamp"], row["published"]
            if datetime.fromisoformat(stamp) > self.cutoff:
                continue
            if stamp not in latest or published > latest[stamp][0]:
                latest[stamp] = (published, float(row["value"]))
        return [latest[key][1] for key in sorted(latest)]

    def write_csv(self, path: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=["timestamp", "value", "published"])
            writer.writeheader()
            for row in self.rows:
                writer.writerow(row)
        return path


def _base_series(rng: random.Random, count: int, season: int) -> list[float]:
    level = rng.uniform(80, 400)
    slope = rng.uniform(-0.4, 0.8)
    amplitude = level * rng.uniform(0.03, 0.12)
    noise = level * rng.uniform(0.01, 0.03)
    return [
        level + slope * index
        + amplitude * math.sin(2 * math.pi * index / season)
        + rng.gauss(0, noise)
        for index in range(count)
    ]


def generate_task(index: int, seed: int, history: int = 120,
                  horizon: int = 14, season: int = 7) -> TrapTask:
    rng = random.Random((seed * 100_003) + index)
    start = datetime(2025, 1, 1, tzinfo=timezone.utc)
    values = _base_series(rng, history + horizon, season)
    cutoff = start + timedelta(days=history - 1)

    understatement = rng.uniform(*REVISION_UNDERSTATEMENT)
    shock = rng.uniform(*SHOCK_MAGNITUDE) * rng.choice((1.0, -1.0))
    level = sum(values[:history]) / history

    rows: list[dict[str, Any]] = []
    for offset in range(history):
        stamp = start + timedelta(days=offset)
        final = values[offset]
        if offset >= history - REVISION_LAG:
            # Published low on the day, corrected after the cutoff. A
            # forecaster at the cutoff sees the understated figure; one that
            # reads the whole file sees the correction.
            rows.append({
                "timestamp": stamp.isoformat(),
                "value": round(final * (1 - understatement), 4),
                "published": stamp.isoformat(),
            })
            rows.append({
                "timestamp": stamp.isoformat(),
                "value": round(final, 4),
                "published": (cutoff + timedelta(days=2)).isoformat(),
            })
        else:
            rows.append({
                "timestamp": stamp.isoformat(),
                "value": round(final, 4),
                "published": stamp.isoformat(),
            })

    truth: list[float] = []
    for step in range(horizon):
        stamp = start + timedelta(days=history + step)
        # The shock: unpredictable from anything published by the cutoff.
        actual = values[history + step] + shock * level
        truth.append(round(actual, 4))
        rows.append({
            "timestamp": stamp.isoformat(),
            "value": round(actual, 4),
            "published": stamp.isoformat(),
        })

    return TrapTask(
        task_id=f"leaktrap-{seed}-{index:04d}",
        rows=rows,
        cutoff=cutoff,
        horizon=horizon,
        truth=truth,
        shock=shock,
        understatement=understatement,
        metadata={
            "history": history, "season": season,
            "level": round(level, 4),
            "revision_lag": REVISION_LAG,
        },
    )


def generate_tasks(count: int, seed: int = 7, **kwargs: Any) -> list[TrapTask]:
    return [generate_task(index, seed, **kwargs) for index in range(count)]
